import type { Argv } from "yargs";
import { verifyDnsToken } from "hibp";
import { config } from "../config.js";
import { apiKeyEpilog } from "../utils/api-key-epilog.js";
import { logger } from "../utils/logger.js";
import { spinner } from "../utils/spinner.js";
import { translateApiError } from "../utils/translate-api-error.js";
import { userAgent } from "../utils/user-agent.js";

export const command = "vdt <domain>";
export const describe = "verify a domain using its published DNS TXT record";

interface VdtArgvOptions {
  domain: string;
  r?: boolean;
}

interface VdtHandlerOptions {
  domain: string;
  raw?: boolean;
}

/* v8 ignore next -- @preserve */
export function builder(yargs: Argv<VdtArgvOptions>): Argv<VdtHandlerOptions> {
  return yargs
    .positional("domain", {
      type: "string",
    })
    .demandOption("domain")
    .check((argv) => {
      if (!argv.domain.length) {
        throw new Error("The domain argument must not be empty.");
      }
      return true;
    })
    .option("r", {
      alias: "raw",
      describe: "disable the console spinner",
      type: "boolean",
      default: false,
    })
    .group(["r"], "Command Options:")
    .group(["h", "v"], "Global Options:")
    .epilog(apiKeyEpilog("Pro"));
}

/**
 * Verifies a domain using the DNS TXT record generated by the "gdt" command.
 *
 * @param {object} argv the parsed argv object
 * @param {string} argv.domain the domain to verify
 * @param {boolean} [argv.raw] disable the console spinner (default: false)
 * @returns {Promise<void>} the resulting Promise where output is rendered
 */
export async function handler({
  domain,
  raw,
}: VdtHandlerOptions): Promise<void> {
  if (!raw) {
    spinner.start();
  }

  try {
    const trimmedDomain = domain.trim();
    await verifyDnsToken(trimmedDomain, {
      apiKey: config.get("apiKey"),
      userAgent,
    });
    const successMessage = `Verified ${trimmedDomain}.`;
    if (!raw) {
      spinner.succeed(successMessage);
    } else {
      logger.log(successMessage);
    }
  } catch (maybeError) {
    /* v8 ignore else -- @preserve */
    if (maybeError instanceof Error) {
      process.exitCode = 1;
      const errorMessage = translateApiError(maybeError.message);
      if (!raw) {
        spinner.fail(errorMessage);
      } else {
        logger.error(errorMessage);
      }
    }
  }
}
